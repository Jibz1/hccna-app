import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

import { Schema } from "effect";

const VERSION_PATTERN = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/;
const NATIVE_VERSION_FILE = "native-version.js";

export const StoreVersion = Schema.Struct({
  version: Schema.String.check(Schema.isPattern(VERSION_PATTERN)),
  androidVersionCode: Schema.Int.check(Schema.isGreaterThan(0)),
});
export type StoreVersion = typeof StoreVersion.Type;
export type BumpKind = "store" | "major";

export function parseVersion(
  version: string,
): readonly [number, number, number] {
  const match = VERSION_PATTERN.exec(version);
  if (!match) {
    throw new Error(
      `${version} is not a MAJOR.STORE.OTA version such as 2.1.0.`,
    );
  }
  return [Number(match[1]), Number(match[2]), Number(match[3])];
}

export function bumpStoreVersion(
  current: StoreVersion,
  kind: BumpKind,
): StoreVersion {
  const [major, store] = parseVersion(current.version);
  return {
    version: kind === "major" ? `${major + 1}.0.0` : `${major}.${store + 1}.0`,
    androidVersionCode: current.androidVersionCode + 1,
  };
}

export const formatNativeVersionFile = (store: StoreVersion) =>
  `// This file is generated by \`bun run version:bump\`. Do not edit it.\nmodule.exports = { version: ${JSON.stringify(store.version)}, androidVersionCode: ${store.androidVersionCode} };\n`;

export function readStoreVersion(projectRoot: string): StoreVersion {
  const projectRequire = createRequire(join(projectRoot, "package.json"));
  try {
    return Schema.decodeUnknownSync(StoreVersion)(
      projectRequire(`./${NATIVE_VERSION_FILE}`),
    );
  } catch (error) {
    throw new Error(
      `${NATIVE_VERSION_FILE} must export { version: "X.Y.Z", androidVersionCode: N }. Restore it from git, then change it only with \`bun run version:bump\`.`,
      { cause: error },
    );
  }
}

export function writeStoreVersion(projectRoot: string, store: StoreVersion) {
  writeFileSync(
    join(projectRoot, NATIVE_VERSION_FILE),
    formatNativeVersionFile(store),
  );
}

const ANDROID_BUILD_GRADLE = join("android", "app", "build.gradle");
const IOS_INFO_PLIST = join("ios", "HCCNA", "Info.plist");

function readGeneratedFile(
  projectRoot: string,
  file: string,
  regenerate: string,
) {
  const path = join(projectRoot, file);
  if (!existsSync(path)) {
    throw new Error(`Cannot find ${file}. Run \`${regenerate}\` first.`);
  }
  return readFileSync(path, "utf8");
}

// expo prebuild copies the numbers into the generated projects as literals;
// release builds read those copies, so an older project would ship old numbers.
export function assertAndroidProjectCurrent(
  projectRoot: string,
  store: StoreVersion,
) {
  const regenerate = "bun run generate--android-native-build";
  const gradle = readGeneratedFile(
    projectRoot,
    ANDROID_BUILD_GRADLE,
    regenerate,
  );
  const versionName = /versionName\s+"([^"]*)"/.exec(gradle)?.[1] ?? "unknown";
  const versionCode = /versionCode\s+(\d+)/.exec(gradle)?.[1] ?? "unknown";
  if (
    versionName !== store.version ||
    versionCode !== String(store.androidVersionCode)
  ) {
    throw new Error(
      `Native project is ${versionName} (${versionCode}) but native-version.js is ${store.version} (${store.androidVersionCode}). Re-run \`${regenerate}\`.`,
    );
  }
}

export function assertIosProjectCurrent(
  projectRoot: string,
  store: StoreVersion,
) {
  const regenerate = "bun run prebuild:release";
  const plist = readGeneratedFile(projectRoot, IOS_INFO_PLIST, regenerate);
  const version =
    /<key>CFBundleShortVersionString<\/key>\s*<string>([^<]*)<\/string>/.exec(
      plist,
    )?.[1] ?? "unknown";
  if (version !== store.version) {
    throw new Error(
      `Native project is ${version} but native-version.js is ${store.version}. Re-run \`${regenerate}\`.`,
    );
  }
}

const OTA_MESSAGE = /^"?(0|[1-9]\d*)\.(0|[1-9]\d*)\.([1-9]\d*) · /;

export type UpdateGroupSummary = {
  readonly message?: string | null;
  readonly isRollBackToEmbedded: boolean;
};

export function storeReleaseParts(
  storeVersion: string,
): readonly [number, number] {
  const [major, store, patch] = parseVersion(storeVersion);
  if (patch !== 0) {
    throw new Error(
      `native-version.js is ${storeVersion}, which predates the versioning scheme. Run \`bun run version:bump store\` first.`,
    );
  }
  return [major, store];
}

// EAS lists update groups without their manifests, so the `X.Y.N · ` message
// prefix the publisher writes is the record of published OTA numbers. eas-cli
// lists each message as `"<message>" (<time> by <actor>)`, so the prefix is
// read from inside the leading quote.
export function nextOtaVersion(
  storeVersion: string,
  groups: readonly UpdateGroupSummary[],
) {
  const [major, store] = storeReleaseParts(storeVersion);
  const published = groups.flatMap(({ message, isRollBackToEmbedded }) => {
    const match = isRollBackToEmbedded ? null : OTA_MESSAGE.exec(message ?? "");
    return match && Number(match[1]) === major && Number(match[2]) === store
      ? [Number(match[3])]
      : [];
  });
  return `${major}.${store}.${Math.max(0, ...published) + 1}`;
}

export const otaMessage = (version: string, message: string) =>
  `${version} · ${message}`;
