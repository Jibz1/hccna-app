import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  loadReleaseEnv,
  PROJECT_ROOT,
  productionEnv,
  run,
  withoutUpdateValues,
} from "./releaseEnv";

const SIGNING_PROPERTY_KEYS = [
  "MYAPP_UPLOAD_STORE_FILE",
  "MYAPP_UPLOAD_KEY_ALIAS",
  "MYAPP_UPLOAD_STORE_PASSWORD",
  "MYAPP_UPLOAD_KEY_PASSWORD",
] as const;

type SigningPropertyKey = (typeof SIGNING_PROPERTY_KEYS)[number];

const PROPERTY_COMMENTS = new Map<SigningPropertyKey, string>([
  ["MYAPP_UPLOAD_STORE_FILE", '# Path to the "keystore" file'],
  [
    "MYAPP_UPLOAD_KEY_ALIAS",
    "# Replace with value of the `keystore.keyAlias` field in the credentials.json file",
  ],
  [
    "MYAPP_UPLOAD_STORE_PASSWORD",
    "# Replace with value of the `keystore.password` field in the credentials.json file",
  ],
  [
    "MYAPP_UPLOAD_KEY_PASSWORD",
    "# Replace with value of the `keystore.keyPassword` field in the credentials.json file",
  ],
]);

const GENERATED_PROPERTIES_START =
  "# Android release signing credentials generated by scripts/generate-android-native-build.ts";
const GENERATED_PROPERTIES_END = "# End Android release signing credentials";

const RELEASE_SIGNING_CONFIG_LINES = [
  "        release {",
  "            if (project.hasProperty('MYAPP_UPLOAD_STORE_FILE')) {",
  "                storeFile file(MYAPP_UPLOAD_STORE_FILE)",
  "                storePassword MYAPP_UPLOAD_STORE_PASSWORD",
  "                keyAlias MYAPP_UPLOAD_KEY_ALIAS",
  "                keyPassword MYAPP_UPLOAD_KEY_PASSWORD",
  "            }",
  "        }",
];

const gradlePropertiesPath = resolve(
  PROJECT_ROOT,
  "android",
  "gradle.properties",
);
const appBuildGradlePath = resolve(
  PROJECT_ROOT,
  "android",
  "app",
  "build.gradle",
);

function main() {
  if (process.argv.includes("--help")) {
    printHelp();
    return;
  }

  // The same explicit release files as prebuild:release; .env*.local and the
  // shell never reach the prebuild or the signing values.
  const releaseValues = loadReleaseEnv();
  const signingProperties = readSigningProperties(releaseValues);
  runExpoPrebuild(
    productionEnv({ ...withoutUpdateValues(), ...releaseValues }),
  );

  updateGradleProperties(signingProperties);
  updateAppBuildGradle();

  console.log("Android native build files generated");
}

function printHelp() {
  console.log(`Usage: bun run generate--android-native-build

Runs expo prebuild --platform android with the release files (.env.production
over .env), copies the Android release signing values from those files into
android/gradle.properties, and updates android/app/build.gradle for release
signing.`);
}

function runExpoPrebuild(env: Record<string, string | undefined>) {
  console.log("Running expo prebuild --platform android...");
  run(
    "node",
    [
      fileURLToPath(import.meta.resolve("expo/bin/cli")),
      "prebuild",
      "--platform",
      "android",
    ],
    { env },
  );
}

function readSigningProperties(env: Record<string, string | undefined>) {
  const signingProperties = new Map<SigningPropertyKey, string>();
  const missingKeys: string[] = [];

  for (const key of SIGNING_PROPERTY_KEYS) {
    const value = env[key];

    if (!value) {
      missingKeys.push(key);
      continue;
    }

    signingProperties.set(key, value);
  }

  if (missingKeys.length > 0) {
    throw new Error(
      `Release environment files are missing Android signing value(s): ${missingKeys.join(", ")}`,
    );
  }

  return signingProperties;
}

function updateGradleProperties(
  signingProperties: Map<SigningPropertyKey, string>,
) {
  const content = readTextFile(gradlePropertiesPath);
  const nextContent = appendSigningPropertiesBlock(content, signingProperties);

  writeFileSync(gradlePropertiesPath, nextContent);
  console.log("Updated android/gradle.properties");
}

function appendSigningPropertiesBlock(
  content: string,
  signingProperties: Map<SigningPropertyKey, string>,
) {
  const signingCommentValues = new Set(PROPERTY_COMMENTS.values());
  const nextLines: string[] = [];
  let isInsideGeneratedBlock = false;

  for (const line of normalizeNewlines(content).split("\n")) {
    const trimmedLine = line.trim();

    if (trimmedLine === GENERATED_PROPERTIES_START) {
      isInsideGeneratedBlock = true;
      continue;
    }

    if (isInsideGeneratedBlock) {
      if (trimmedLine === GENERATED_PROPERTIES_END) {
        isInsideGeneratedBlock = false;
      }

      continue;
    }

    const isSigningProperty = SIGNING_PROPERTY_KEYS.some((key) =>
      trimmedLine.startsWith(`${key}=`),
    );
    const isSigningComment = signingCommentValues.has(trimmedLine);

    if (isSigningProperty || isSigningComment) {
      continue;
    }

    nextLines.push(line);
  }

  while (nextLines.at(-1)?.trim() === "") {
    nextLines.pop();
  }

  return `${nextLines.join("\n")}\n\n${formatSigningPropertiesBlock(signingProperties)}\n`;
}

function formatSigningPropertiesBlock(
  signingProperties: Map<SigningPropertyKey, string>,
) {
  const lines = [GENERATED_PROPERTIES_START];

  for (const key of SIGNING_PROPERTY_KEYS) {
    const value = signingProperties.get(key);
    const comment = PROPERTY_COMMENTS.get(key);

    if (!value || !comment) {
      throw new Error(`Missing signing property metadata for ${key}`);
    }

    lines.push(`${key}=${escapeGradlePropertyValue(value)}`);
    lines.push(comment);
  }

  lines.push(GENERATED_PROPERTIES_END);

  return lines.join("\n");
}

function escapeGradlePropertyValue(value: string) {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r");
}

function updateAppBuildGradle() {
  const content = readTextFile(appBuildGradlePath);
  const lines = splitLines(content);

  upsertReleaseSigningConfig(lines);
  updateReleaseBuildTypeSigningConfig(lines);

  writeFileSync(appBuildGradlePath, `${lines.join("\n")}\n`);
  console.log("Updated android/app/build.gradle");
}

function upsertReleaseSigningConfig(lines: string[]) {
  const signingConfigsBlock = findBlock(lines, "signingConfigs");

  if (!signingConfigsBlock) {
    throw new Error(
      "Could not find signingConfigs block in android/app/build.gradle",
    );
  }

  const existingReleaseBlock = findBlock(lines, "release", {
    start: signingConfigsBlock.start + 1,
    end: signingConfigsBlock.end,
  });

  if (existingReleaseBlock) {
    lines.splice(
      existingReleaseBlock.start,
      existingReleaseBlock.end - existingReleaseBlock.start + 1,
      ...RELEASE_SIGNING_CONFIG_LINES,
    );
    return;
  }

  lines.splice(signingConfigsBlock.end, 0, ...RELEASE_SIGNING_CONFIG_LINES);
}

function updateReleaseBuildTypeSigningConfig(lines: string[]) {
  const buildTypesBlock = findBlock(lines, "buildTypes");

  if (!buildTypesBlock) {
    throw new Error(
      "Could not find buildTypes block in android/app/build.gradle",
    );
  }

  const releaseBuildTypeBlock = findBlock(lines, "release", {
    start: buildTypesBlock.start + 1,
    end: buildTypesBlock.end,
  });

  if (!releaseBuildTypeBlock) {
    throw new Error(
      "Could not find buildTypes.release block in android/app/build.gradle",
    );
  }

  for (
    let index = releaseBuildTypeBlock.start + 1;
    index < releaseBuildTypeBlock.end;
    index += 1
  ) {
    if (/^\s*signingConfig\s+signingConfigs\.\w+\s*$/.test(lines[index])) {
      lines[index] =
        `${getLineIndent(lines[index])}signingConfig signingConfigs.release`;
      return;
    }
  }

  lines.splice(
    releaseBuildTypeBlock.start + 1,
    0,
    `${getBlockChildIndent(lines[releaseBuildTypeBlock.start])}signingConfig signingConfigs.release`,
  );
}

function findBlock(
  lines: string[],
  blockName: string,
  range: { start: number; end: number } = { start: 0, end: lines.length - 1 },
) {
  const blockStartPattern = new RegExp(
    `^\\s*${escapeRegExp(blockName)}\\s*\\{`,
  );

  for (let index = range.start; index <= range.end; index += 1) {
    if (!blockStartPattern.test(lines[index])) {
      continue;
    }

    let depth = countBraces(lines[index]);

    for (let endIndex = index + 1; endIndex <= range.end; endIndex += 1) {
      depth += countBraces(lines[endIndex]);

      if (depth === 0) {
        return { start: index, end: endIndex };
      }
    }

    throw new Error(`Could not find closing brace for ${blockName} block`);
  }

  return null;
}

function countBraces(line: string) {
  const lineWithoutStrings = line
    .replace(/"([^"\\]|\\.)*"/g, '""')
    .replace(/'([^'\\]|\\.)*'/g, "''");

  return (
    (lineWithoutStrings.match(/\{/g)?.length ?? 0) -
    (lineWithoutStrings.match(/\}/g)?.length ?? 0)
  );
}

function getLineIndent(line: string) {
  return line.match(/^\s*/)?.[0] ?? "";
}

function getBlockChildIndent(blockStartLine: string) {
  return `${getLineIndent(blockStartLine)}    `;
}

function readTextFile(filePath: string) {
  if (!existsSync(filePath)) {
    throw new Error(`Expected file to exist after prebuild: ${filePath}`);
  }

  return readFileSync(filePath, "utf8");
}

function splitLines(content: string) {
  const lines = normalizeNewlines(content).split("\n");

  if (lines.at(-1) === "") {
    lines.pop();
  }

  return lines;
}

function normalizeNewlines(content: string) {
  return content.replace(/\r\n?/g, "\n");
}

function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
